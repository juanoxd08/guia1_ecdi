import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import odeint

# Definimos la ecuación diferencial autónoma
def f(P, t):
    return P * (P - 1) * (2 - P)

# Rango de tiempo
t_vals = np.linspace(0, 0.5, 200)

# Condiciones iniciales específicas
condiciones_iniciales = [3000]

plt.figure(figsize=(8,6))

# Resolver y graficar cada solución
for P0 in condiciones_iniciales:
    sol = odeint(f, P0, t_vals)
    plt.plot(t_vals, sol, label=f"P(0)={P0}")

# Configuración del gráfico
plt.title("Condición inicial 3000")
plt.xlabel("t")
plt.ylabel("P(t)")
plt.legend()
plt.grid(True)
plt.show()

